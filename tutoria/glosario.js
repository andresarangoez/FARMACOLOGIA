window.anotarSiglas = function (texto, formato) {
  var esc = function (s) { return String(s).replace(/[&<>"']/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]; }); };
  var M = {}; window.SIGLAS.forEach(function (s) { M[s[0]] = s[1]; });
  var re = new RegExp("(^|[^A-Za-z0-9])(" + window.SIGLAS.map(function (s) { return s[0].replace(/[.*+?^${}()|[]\/]/g, "\$&"); }).join("|") + ")(?![A-Za-z0-9]|-[0-9])", "g");
  var usadas = {}, out = "", ult = 0, m;
  while ((m = re.exec(texto))) {
    var s = m[2], fin = m.index + m[0].length;
    out += esc(texto.slice(ult, fin)); ult = fin;
    if (!usadas[s]) { usadas[s] = 1; out += formato(M[s]); }
  }
  return out + esc(texto.slice(ult));
};
